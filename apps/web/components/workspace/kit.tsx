import type { LucideIcon } from "lucide-react";
import { CircleCheck, CircleX, Sparkles } from "lucide-react";
import type { Transaction } from "@baa/core";
import { cn, daysAgo, shortDate, usd } from "@/lib/utils";

/** Header shared by the three workspace columns - compact, flat design. */
export function PanelHeader({
  icon: Icon,
  title,
  meta,
  children,
}: {
  icon: LucideIcon;
  title: string;
  meta?: React.ReactNode;
  children?: React.ReactNode;
}) {
  return (
    <div className="flex h-10 shrink-0 items-center gap-2 border-b border-border bg-surface px-3 dark:bg-surface-elevated">
      <Icon className="size-3.5 text-muted-foreground" />
      <h2 className="shrink-0 text-[13px] font-medium text-foreground">{title}</h2>
      {meta && (
        <span className="truncate text-[11px] font-medium tracking-wide text-muted-foreground uppercase">{meta}</span>
      )}
      {children && <div className="ml-auto flex items-center gap-1.5">{children}</div>}
    </div>
  );
}

/** Small "AI" marker used wherever content was generated by the model. */
export function AiLabel({ children = "AI", className }: { children?: React.ReactNode; className?: string }) {
  return (
    <span className={cn("inline-flex items-center gap-1 text-xs font-medium text-ai", className)}>
      <Sparkles className="size-3.5" />
      {children}
    </span>
  );
}

/** Uppercase eyebrow label for groups inside a card. */
export function Eyebrow({
  icon: Icon,
  children,
  className,
}: {
  icon?: LucideIcon;
  children: React.ReactNode;
  className?: string;
}) {
  return (
    <p
      className={cn(
        "flex items-center gap-1.5 text-[11px] font-medium tracking-wide text-muted-foreground uppercase",
        className,
      )}
    >
      {Icon && <Icon className="size-3.5" />}
      {children}
    </p>
  );
}

export function KeyValue({
  label,
  children,
  className,
}: {
  label: string;
  children: React.ReactNode;
  className?: string;
}) {
  return (
    <div className={cn("flex items-baseline justify-between gap-4 text-sm", className)}>
      <dt className="shrink-0 text-muted-foreground">{label}</dt>
      <dd className="min-w-0 truncate text-right font-medium">{children}</dd>
    </div>
  );
}

export function Amount({ value, className }: { value: number; className?: string }) {
  return (
    <span className={cn("font-mono tabular-nums", value < 0 && "text-success", className)}>
      {value < 0 ? `+${usd(-value)}` : usd(value)}
    </span>
  );
}

export function CheckIcon({ passed, className }: { passed: boolean; className?: string }) {
  return passed ? (
    <CircleCheck className={cn("size-4 shrink-0 text-success", className)} />
  ) : (
    <CircleX className={cn("size-4 shrink-0 text-destructive", className)} />
  );
}

/** One-line description of a transaction: merchant and amount, then date, channel and status. */
export function TransactionSummary({ t, className }: { t: Transaction; className?: string }) {
  return (
    <div className={cn("flex items-start justify-between gap-3", className)}>
      <div className="min-w-0">
        <div className="truncate text-[14px] font-medium">{t.merchant}</div>
        <div className="text-[13px] text-muted-foreground">
          {shortDate(t.date)} · {daysAgo(t.daysAgo)} · {t.channel === "online" ? "Online" : "In store"} ·{" "}
          <span className="capitalize">{t.status}</span>
        </div>
      </div>
      <Amount value={t.amount} className="text-[15px] font-semibold" />
    </div>
  );
}
